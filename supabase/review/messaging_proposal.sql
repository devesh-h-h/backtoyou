-- REVIEW-ONLY PROPOSAL. Do not apply without verifying the deployed
-- profiles, claims, lost_items, and found_items schemas, grants, and RLS.
--
-- The current repository identifies participants by authenticated email.
-- Replace participant_email with verified auth.users.id foreign keys after
-- the baseline schema is migrated to a trusted user-id ownership model.
--
-- Conversations are created by the approval trigger only. There is no
-- authenticated insert policy for conversations.

create table if not exists public.conversations (
  id bigint generated by default as identity primary key,
  claim_id bigint not null unique references public.claims(id) on delete cascade,
  claimant_email text not null,
  finder_email text not null,
  created_at timestamptz not null default now(),
  closed_at timestamptz,
  constraint conversations_distinct_participants
    check (claimant_email <> finder_email)
);

create index if not exists conversations_claimant_email
  on public.conversations (claimant_email);

create index if not exists conversations_finder_email
  on public.conversations (finder_email);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.conversations(id) on delete cascade,
  sender_email text not null,
  body text not null check (char_length(trim(body)) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists messages_conversation_created_at
  on public.messages (conversation_id, created_at, id);

alter table public.conversations enable row level security;
alter table public.messages enable row level security;

create policy "Conversation participants can read active conversations"
  on public.conversations
  for select
  to authenticated
  using (
    (
      claimant_email = auth.jwt() ->> 'email'
      or finder_email = auth.jwt() ->> 'email'
    )
    and exists (
      select 1
      from public.claims c
      join public.found_items f on f.id = c.item_id
      where c.id = conversations.claim_id
        and c.status = 'approved'
        and (
          c.claimant_email = auth.jwt() ->> 'email'
          or f.user_email = auth.jwt() ->> 'email'
        )
    )
  );

create policy "Conversation participants can read messages"
  on public.messages
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.conversations c
      join public.claims cl on cl.id = c.claim_id
      join public.found_items f on f.id = cl.item_id
      where c.id = messages.conversation_id
        and cl.status = 'approved'
        and (
          c.claimant_email = auth.jwt() ->> 'email'
          or c.finder_email = auth.jwt() ->> 'email'
        )
        and (
          cl.claimant_email = auth.jwt() ->> 'email'
          or f.user_email = auth.jwt() ->> 'email'
        )
    )
  );

create policy "Open conversation participants can send messages"
  on public.messages
  for insert
  to authenticated
  with check (
    sender_email = auth.jwt() ->> 'email'
    and exists (
      select 1
      from public.conversations c
      join public.claims cl on cl.id = c.claim_id
      join public.found_items f on f.id = cl.item_id
      where c.id = messages.conversation_id
        and c.closed_at is null
        and cl.status = 'approved'
        and f.status = 'claimed'
        and (
          c.claimant_email = auth.jwt() ->> 'email'
          or c.finder_email = auth.jwt() ->> 'email'
        )
        and (
          cl.claimant_email = auth.jwt() ->> 'email'
          or f.user_email = auth.jwt() ->> 'email'
        )
    )
  );

-- Messages are append-only. Clients cannot rewrite sender, body, ownership,
-- conversation membership, or timestamps after insertion.
create or replace function public.prevent_message_changes()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  raise exception 'Messages cannot be changed or deleted';
end;
$$;

drop trigger if exists prevent_message_changes on public.messages;
create trigger prevent_message_changes
before update or delete on public.messages
for each row execute function public.prevent_message_changes();

-- Only an approved claim creates a conversation, and both participant
-- addresses are read from the claim/report relationship in the database.
create or replace function public.create_approved_claim_conversation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'approved' and old.status is distinct from 'approved' then
    insert into public.conversations (
      claim_id,
      claimant_email,
      finder_email
    )
    select
      new.id,
      new.claimant_email,
      f.user_email
    from public.found_items f
    where f.id = new.item_id
      and f.user_email is not null
      and new.claimant_email <> f.user_email
    on conflict (claim_id) do nothing;
  end if;

  return new;
end;
$$;

drop trigger if exists create_approved_claim_conversation on public.claims;
create trigger create_approved_claim_conversation
after update of status on public.claims
for each row execute function public.create_approved_claim_conversation();

-- Rejection or any later loss of approval closes the conversation. A returned
-- item is read-only: existing messages remain available to the participants,
-- but new messages are blocked by the insert policy above.
create or replace function public.close_claim_conversation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status is distinct from 'approved' then
    update public.conversations
    set closed_at = coalesce(closed_at, now())
    where claim_id = new.id;
  end if;

  return new;
end;
$$;

drop trigger if exists close_claim_conversation on public.claims;
create trigger close_claim_conversation
after update of status on public.claims
for each row execute function public.close_claim_conversation();

create or replace function public.close_returned_item_conversations()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'returned' and old.status is distinct from 'returned' then
    update public.conversations c
    set closed_at = coalesce(c.closed_at, now())
    from public.claims cl
    where c.claim_id = cl.id
      and cl.item_id = new.id;
  end if;

  return new;
end;
$$;

drop trigger if exists close_returned_item_conversations on public.found_items;
create trigger close_returned_item_conversations
after update of status on public.found_items
for each row execute function public.close_returned_item_conversations();

revoke all on function public.create_approved_claim_conversation() from public;
revoke all on function public.close_claim_conversation() from public;
revoke all on function public.close_returned_item_conversations() from public;
revoke all on function public.prevent_message_changes() from public;

grant select on public.conversations to authenticated;
grant select, insert on public.messages to authenticated;
