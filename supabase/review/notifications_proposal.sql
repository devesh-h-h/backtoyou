-- REVIEW-ONLY PROPOSAL. Do not apply without verifying the deployed
-- profiles, claims, lost_items, and found_items schemas and RLS policies.
--
-- The current application identifies users by authenticated email. This
-- proposal keeps that identity model until a verified auth user-id column is
-- available in the baseline schema. Do not accept client-created rows.

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_email text not null,
  notification_type text not null check (
    notification_type in (
      'claim_approved',
      'claim_rejected',
      'claim_submitted',
      'item_returned'
    )
  ),
  claim_id bigint references public.claims(id) on delete cascade,
  report_id bigint references public.found_items(id) on delete cascade,
  message text not null check (char_length(trim(message)) between 1 and 500),
  created_at timestamptz not null default now(),
  read_at timestamptz,
  constraint notifications_claim_event_reference check (
    (notification_type in ('claim_approved', 'claim_rejected', 'claim_submitted') and claim_id is not null)
    or (notification_type = 'item_returned' and report_id is not null)
  )
);

create unique index if not exists notifications_one_claim_event_per_recipient
  on public.notifications (recipient_email, notification_type, claim_id)
  where claim_id is not null;

create unique index if not exists notifications_one_return_event_per_recipient
  on public.notifications (recipient_email, notification_type, report_id)
  where report_id is not null;

create index if not exists notifications_recipient_created_at
  on public.notifications (recipient_email, created_at desc);

alter table public.notifications enable row level security;

create policy "Users can read their own notifications"
  on public.notifications
  for select
  to authenticated
  using (recipient_email = auth.jwt() ->> 'email');

create policy "Users can mark their own notifications read"
  on public.notifications
  for update
  to authenticated
  using (recipient_email = auth.jwt() ->> 'email')
  with check (recipient_email = auth.jwt() ->> 'email');

-- There is deliberately no authenticated insert policy. Notifications are
-- created only by the trusted trigger functions below.

create or replace function public.create_claim_notification()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  event_type text;
  event_message text;
begin
  if tg_op = 'INSERT' then
    insert into public.notifications (
      recipient_email,
      notification_type,
      claim_id,
      message
    )
    select
      f.user_email,
      'claim_submitted',
      new.id,
      'A new claim was submitted for your found-item report.'
    from public.found_items f
    where f.id = new.item_id
      and f.user_email is not null
    on conflict do nothing;

    return new;
  end if;

  if new.status = old.status
     or new.status not in ('approved', 'rejected') then
    return new;
  end if;

  event_type := case
    when new.status = 'approved' then 'claim_approved'
    else 'claim_rejected'
  end;

  event_message := case
    when new.status = 'approved'
      then 'Your claim was approved. Review the approved contact options.'
    else 'Your claim was rejected. Review the claim details for more information.'
  end;

  insert into public.notifications (
    recipient_email,
    notification_type,
    claim_id,
    message
  )
  values (
    new.claimant_email,
    event_type,
    new.id,
    event_message
  )
  on conflict do nothing;

  return new;
end;
$$;

create or replace function public.create_returned_item_notification()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'returned' and old.status is distinct from 'returned' then
    insert into public.notifications (
      recipient_email,
      notification_type,
      claim_id,
      report_id,
      message
    )
    select
      c.claimant_email,
      'item_returned',
      c.id,
      new.id,
      'The found item connected to your approved claim was marked returned.'
    from public.claims c
    where c.item_id = new.id
      and c.status = 'approved'
    on conflict do nothing;
  end if;

  return new;
end;
$$;

drop trigger if exists create_claim_notification on public.claims;
create trigger create_claim_notification
after insert or update of status on public.claims
for each row execute function public.create_claim_notification();

drop trigger if exists create_returned_item_notification on public.found_items;
create trigger create_returned_item_notification
after update of status on public.found_items
for each row execute function public.create_returned_item_notification();

revoke all on function public.create_claim_notification() from public;
revoke all on function public.create_returned_item_notification() from public;
grant select, update on public.notifications to authenticated;

create or replace function public.prevent_notification_content_changes()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.recipient_email is distinct from old.recipient_email
     or new.notification_type is distinct from old.notification_type
     or new.claim_id is distinct from old.claim_id
     or new.report_id is distinct from old.report_id
     or new.message is distinct from old.message
     or new.created_at is distinct from old.created_at then
    raise exception 'Notification event data cannot be changed';
  end if;

  if old.read_at is not null and new.read_at is null then
    raise exception 'A notification cannot be marked unread';
  end if;

  return new;
end;
$$;

drop trigger if exists prevent_notification_content_changes on public.notifications;
create trigger prevent_notification_content_changes
before update on public.notifications
for each row execute function public.prevent_notification_content_changes();

revoke all on function public.prevent_notification_content_changes() from public;
